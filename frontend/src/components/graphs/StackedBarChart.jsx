// 4.3 Stacked bar chart of median or average values of a selected quantity over time
// A stacked bar chart with a bar for each year, and with each bar segmented to show
//     1. a breakdown of total investments by investment. (If possible, visually indicate the tax status of
//     the account containing the investment, and use adjacent segments for investments with the
//     same tax status.), or
//     2. a breakdown of income by event series (note that income generated by investments is not
//     associated with an event series hence is not included in this chart), or
//     3. a breakdown of expenses by event series, plus a segment for taxes
// The user selects whether to use median or average values. For example, if the user selects average
// values for the investments chart, the height of each segment of the bar for year Y is the average value
// (across the set of simulations) in year Y of one of the investments. To avoid clutter, the user can specify
// an aggregation threshold. Categories whose values are below that threshold in every year of every
// simulation are aggregated and displayed as a single “Other” category. Hovering over a bar raises a pop-
// up displaying the height of the bar and the height of each segment.

// TP - ChatGPT - Was asked to create functions for calculating the median and average of an array of numbers.
//                       Was also asked to create a function that generates a random color in RGBA format.
function getMedian(values) {
    values.sort((a, b) => a - b);
    const mid = Math.floor(values.length / 2);
    return values.length % 2 !== 0
    ? values[mid]
    : (values[mid - 1] + values[mid]) / 2;
}    

function getAverage(values) {
    const sum = values.reduce((a, b) => a + b, 0);
    return sum / values.length;
}

const getRandomColor = () => {
    const r = Math.floor(Math.random() * 256);
    const g = Math.floor(Math.random() * 256);
    const b = Math.floor(Math.random() * 256);
    return `rgba(${r}, ${g}, ${b}, 0.8)`; // Random color with 80% opacity
};

