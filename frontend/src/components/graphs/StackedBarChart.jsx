import React from 'react';
import { Bar } from 'react-chartjs-2';
import { Chart as ChartJS, CategoryScale, LinearScale, BarElement, Title, Tooltip, Legend } from 'chart.js';

// Register Chart.js components
ChartJS.register(CategoryScale, LinearScale, BarElement, Title, Tooltip, Legend);

// 4.3 Stacked bar chart of median or average values of a selected quantity over time
// A stacked bar chart with a bar for each year, and with each bar segmented to show
//     1. a breakdown of total investments by investment. (If possible, visually indicate the tax status of
//     the account containing the investment, and use adjacent segments for investments with the
//     same tax status.), or
//     2. a breakdown of income by event series (note that income generated by investments is not
//     associated with an event series hence is not included in this chart), or
//     3. a breakdown of expenses by event series, plus a segment for taxes
// The user selects whether to use median or average values. For example, if the user selects average
// values for the investments chart, the height of each segment of the bar for year Y is the average value
// (across the set of simulations) in year Y of one of the investments. To avoid clutter, the user can specify
// an aggregation threshold. Categories whose values are below that threshold in every year of every
// simulation are aggregated and displayed as a single “Other” category. Hovering over a bar raises a pop-
// up displaying the height of the bar and the height of each segment.

// TP - Github Copilot - Was fed the description from the requirements document as a prompt.
//                       The code required heavy editing however.

const StackedBarChart = ({scenario, simulationResults }) => {
    const yearlyData = simulationResults.result.yearlyData;

    // Extract data for the chart
    const labels = yearlyData.map(data => data.year);

    // Example data for stacked bars (replace with actual calculations)
    const investmentCategories = ['Stocks', 'Bonds', 'Real Estate', 'Cash'];
    const investmentsData = investmentCategories.map(category =>
        yearlyData.map(data => {
            const investment = data.investments.find(inv => inv.type.toLowerCase() === category.toLowerCase());
            return investment ? investment.value : 0;
        })
    );

    const data = {
        labels,
        datasets: investmentCategories.map((category, index) => ({
            label: category,
            data: investmentsData[index],
            backgroundColor: [
                'rgba(75, 192, 192, 0.8)', // Stocks
                'rgba(54, 162, 235, 0.8)', // Bonds
                'rgba(255, 206, 86, 0.8)', // Real Estate
                'rgba(153, 102, 255, 0.8)', // Cash
            ][index],
            borderWidth: 1,
        })),
    };

    const options = {
        responsive: true,
        plugins: {
            legend: {
                position: 'top',
            },
            title: {
                display: true,
                text: 'Stacked Bar Chart of Investments Over Time',
            },
            tooltip: {
                callbacks: {
                    label: function (context) {
                        return `${context.dataset.label}: $${context.raw.toLocaleString()}`;
                    },
                },
            },
        },
        scales: {
            x: {
                stacked: true,
                title: {
                    display: true,
                    text: 'Years',
                },
            },
            y: {
                stacked: true,
                beginAtZero: true,
                title: {
                    display: true,
                    text: 'Investment Value ($)',
                },
            },
        },
    };

    return <Bar data={data} options={options} />;
};

export default StackedBarChart;